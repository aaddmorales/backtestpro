-- Guard: recusa rodar num banco sem a sentinela de isolamento criada logo abaixo
-- na primeira aplicacao (banco vazio) -- em banco com tabelas e sem sentinela, aborta.
DO $$
BEGIN
  IF to_regclass('public._bt_homolog_marker') IS NULL
     AND to_regclass('public.conector_bots') IS NOT NULL THEN
    RAISE EXCEPTION 'ABORTADO: banco com conector_bots e sem _bt_homolog_marker (parece producao)';
  END IF;
END $$;

