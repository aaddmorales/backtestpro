CREATE OR REPLACE FUNCTION public._mt5_expirar_comandos() RETURNS void
LANGUAGE sql AS $$
  UPDATE public.mt5_comandos SET status='expirado'
   WHERE status='pendente' AND expira_em IS NOT NULL AND expira_em < now() $$;

-- RLS: o front (anon key + JWT do usuario) so le o proprio perfil e os proprios bots;
-- todo o resto e service_role (api). Default deny.
DO $$ DECLARE t text; BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname='public' LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('GRANT ALL ON public.%I TO service_role', t);
  END LOOP; END $$;
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
GRANT SELECT ON public.perfis, public.conector_bots TO authenticated;
DROP POLICY IF EXISTS perfis_proprio ON public.perfis;
CREATE POLICY perfis_proprio ON public.perfis FOR SELECT TO authenticated USING (id = auth.uid());
DROP POLICY IF EXISTS bots_proprios ON public.conector_bots;
CREATE POLICY bots_proprios ON public.conector_bots FOR SELECT TO authenticated USING (user_id = auth.uid());
