  id int PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  ambiente text NOT NULL DEFAULT 'isolado-local',
  criado_em timestamptz NOT NULL DEFAULT now());
INSERT INTO public._bt_homolog_marker(id) VALUES (1) ON CONFLICT DO NOTHING;

