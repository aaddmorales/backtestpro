CREATE OR REPLACE FUNCTION public._bt_perfil_novo() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  INSERT INTO public.perfis(id, email) VALUES (NEW.id, NEW.email)
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_bt_perfil_novo ON auth.users;
CREATE TRIGGER trg_bt_perfil_novo AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public._bt_perfil_novo();

